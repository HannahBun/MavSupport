package SeniorSupportHub;

public class HubUser {
	protected String name;
	protected String number;
	protected String email;
	protected String bio; 
	
	public HubUser(String name, String number, String email, String bio) {
		this.name= name;
		this.number= number;
		this.email= email;
		this.bio = bio;
	}
	
}
